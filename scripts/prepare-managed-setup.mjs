import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const migration = (name) =>
  readFileSync(join(root, 'supabase', 'migrations', name), 'utf8')
    .replace(/^\s*(?:BEGIN|COMMIT);\s*$/gm, '')
    .trim();
const schema = migration('067_managed_automation.sql');
if (schema.includes('$managed_schema$'))
  throw new Error('Migration delimiter conflict');
const sql = `-- Generated by npm run managed:prepare-setup. Review before running.
-- Run in your Supabase project's SQL Editor as the database administrator.
-- Requires the existing application migrations through 064.
-- This script does not grant platform administration, activate subscriptions,
-- charge payments, send messages or enable managed registration.
BEGIN;
DO $prerequisites$
BEGIN
  IF to_regclass('public.quotations') IS NULL OR to_regclass('public.ai_configs') IS NULL THEN
    RAISE EXCEPTION 'Apply application migrations 001 through 064 before managed setup';
  END IF;
END $prerequisites$;

-- 065: AI receptionist configuration (safe to rerun).
${migration('065_ai_receptionist.sql')}

-- 066: WhatsApp connection metadata and coexistence (safe to rerun).
${migration('066_whatsapp_coexistence.sql')}

-- 067: Install once; do not recreate existing subscription/payment records.
DO $managed_install$
BEGIN
  IF to_regclass('public.managed_subscriptions') IS NULL THEN
    EXECUTE $managed_schema$
${schema}
$managed_schema$;
  ELSIF to_regclass('public.managed_platform_settings') IS NULL
    OR to_regprocedure('public.managed_permissions(uuid)') IS NULL THEN
    RAISE EXCEPTION 'Managed schema is incomplete. Review migration 067 before proceeding';
  END IF;
END $managed_install$;

-- 068: Preserve service history during membership changes (safe to rerun).
${migration('068_managed_account_integrity.sql')}

NOTIFY pgrst, 'reload schema';
COMMIT;
`;
const target = join(root, 'supabase', 'setup', 'managed-automation.sql');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, sql);
console.log(
  'Prepared supabase/setup/managed-automation.sql (migrations 065–068).'
);
